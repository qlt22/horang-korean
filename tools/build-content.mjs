#!/usr/bin/env node
// Merge docs/content/a1/u*.json → app/data/a1.js (the single source the app imports).
import fs from 'node:fs';
import path from 'node:path';

const DIR = 'docs/content/a1';
const OUT = 'app/data/a1.js';

const files = fs
  .readdirSync(DIR)
  .filter((f) => /^u\d\d\.json$/.test(f))
  .sort();
if (!files.length) {
  console.error('No unit files in ' + DIR);
  process.exit(1);
}

const units = [];
const lessons = [];
const sentences = [];
const words = [];
const grammar = [];
const dialogues = [];
const readings = [];

for (const file of files) {
  const d = JSON.parse(fs.readFileSync(path.join(DIR, file), 'utf8'));
  units.push(d.unit);
  lessons.push(...(d.lessons || []));
  sentences.push(...(d.sentences || []));
  words.push(...(d.words || []));
  grammar.push(...(d.grammar || []));
  if (d.dialogue) dialogues.push(d.dialogue);
  if (d.reading) readings.push(d.reading);
}

units.sort((a, b) => a.order - b.order);
lessons.sort((a, b) => {
  const ua = units.find((u) => u.id === a.unitId)?.order || 0;
  const ub = units.find((u) => u.id === b.unitId)?.order || 0;
  return ua - ub || a.order - b.order;
});
let nodeIndex = 0;
lessons.forEach((l) => {
  l.nodeIndex = nodeIndex++;
});
grammar.sort((a, b) => {
  const ua = units.find((u) => u.id === a.unitId)?.order || 0;
  const ub = units.find((u) => u.id === b.unitId)?.order || 0;
  return ua - ub || a.order - b.order;
});
sentences.sort((a, b) => {
  const la = lessons.find((l) => l.id === a.lessonId)?.nodeIndex ?? 0;
  const lb = lessons.find((l) => l.id === b.lessonId)?.nodeIndex ?? 0;
  return la - lb;
});
words.sort((a, b) => {
  const la = lessons.find((l) => l.id === a.lessonId)?.nodeIndex ?? 0;
  const lb = lessons.find((l) => l.id === b.lessonId)?.nodeIndex ?? 0;
  return la - lb;
});

// Attach the unit's lesson ids to each unit (handy for the course map).
units.forEach((u) => {
  u.lessonIds = lessons.filter((l) => l.unitId === u.id).map((l) => l.id);
  u.lessonCount = u.lessonIds.length;
});

const data = {
  meta: {
    version: '2.0.0',
    cefr: 'A1',
    scope: 'hangul_literate_absolute_beginner',
    register: 'polite 해요체',
    romanization: 'Revised Romanization',
    unitCount: units.length,
    lessonCount: lessons.length,
    sentenceCount: sentences.length,
    wordCount: words.length,
    grammarCount: grammar.length,
    dialogueCount: dialogues.length,
    readingCount: readings.length,
    voices: {
      main: 'ko-KR-SunHiNeural',
      second: 'ko-KR-InJoonNeural',
      engine: 'edge-tts (Microsoft neural)',
    },
  },
  units,
  lessons,
  sentences,
  words,
  grammar,
  dialogues,
  readings,
};

const header = `// AUTO-GENERATED by tools/build-content.mjs — do not hand-edit.
// Source: docs/content/a1/*.json · CEFR A1 · ${sentences.length} sentences / ${words.length} words.
`;
fs.mkdirSync('app/data', { recursive: true });
fs.writeFileSync(OUT, header + 'const DATA = ' + JSON.stringify(data, null, 1) + ';\nexport default DATA;\n');

console.log(`✓ ${OUT}`);
console.log(
  `  ${units.length} units · ${lessons.length} sessions · ${sentences.length} sentences · ${words.length} words · ${grammar.length} grammar · ${dialogues.length} dialogues · ${readings.length} readings`
);
console.log(`  ${(fs.statSync(OUT).size / 1024).toFixed(0)} KB`);
